import { expect, it } from 'vitest';
import { createReplay } from '../../simulation/replay';
import { createPlay } from '../../simulation/play';
it('records independent snapshots and replays without changing live score or clock', () => {
  const state = createPlay();
  const replay = createReplay();
  state.phase = 'live';
  state.carrier = 'qb';
  replay.record(state, 1 / 30);
  state.ball.x = 10;
  state.elapsed = 1;
  replay.record(state, 1 / 30);
  state.phase = 'finished';
  state.drive.score = 6;
  replay.record(state, 1 / 30);
  const before = JSON.stringify(state);
  replay.start();
  const first = replay.sample(0)!;
  expect(first.ball.x).toBe(-19);
  replay.sample(1);
  expect(replay.playing).toBe(false);
  expect(JSON.stringify(state)).toBe(before);
});
it('cannot replay an unfinished play and clears the old recording for a new play', () => {
  const replay = createReplay();
  const state = createPlay();
  state.phase = 'live';
  replay.record(state, 1 / 30);
  replay.start();
  expect(replay.playing).toBe(false);
  state.phase = 'finished';
  replay.record(state, 1 / 30);
  expect(replay.canPlay()).toBe(true);
  replay.record(createPlay(), 1 / 30);
  expect(replay.canPlay()).toBe(false);
});
it('supports slow playback and manual stop', () => {
  const replay = createReplay();
  const state = createPlay();
  state.phase = 'live';
  replay.record(state, 1 / 30);
  state.ball.x = 10;
  replay.record(state, 1 / 30);
  state.phase = 'finished';
  replay.record(state, 1 / 30);
  replay.start();
  expect(replay.sample(1 / 30, 0.5)!.ball.x).toBe(-19);
  expect(replay.playing).toBe(true);
  replay.stop();
  expect(replay.playing).toBe(false);
});
